#!/usr/bin/env python3
"""Generate the OZKIE app's Makefile from the SDK's app_mcu EIDE project
(ozkey-49 P4 item 5b). Derived from vendor/ak1037/ourtools/gen_mk.py.

The SDK's app_mcu is a demo: every app_mcu/sample/*.c registers shell
commands, which the linker keeps (KEEP(FSymTab)), and those pull in an MP3
decoder, a fingerprint matcher, LCD and RFID drivers, and so on. This drops
all of app_mcu/sample and the SDK's main.c, and builds port/ak1037/app/
main_ozkie.c instead. Two features stay optional until the product rules:

  --fp     fingerprint: the platform fingerprint component (it registers its
           own command, which keeps libfp_btl in) and the SDK's fp.* sample
  --voice  voice prompts: the SDK's audio component and its audio.* sample
           player (the MP3 decoder only links if something plays)

Everything else (compiler flags, includes, linker script, libraries) is the
SDK project's own, so the platform objects are identical to the reference.

usage: gen_app_mk.py <sdk_root> <ozcore_dir_relative_to_app_mcu> <out> [--fp] [--voice]
make runs from app_mcu, e.g. make -f Makefile.ozkie_fp1_v1
"""
import json, os, sys

args = [a for a in sys.argv[1:] if not a.startswith('--')]
flags = {a for a in sys.argv[1:] if a.startswith('--')}
if len(args) != 3 or flags - {'--fp', '--voice'}:
    sys.exit(__doc__)
sdk, ozrel, out = args
fp, voice = '--fp' in flags, '--voice' in flags
pdir = os.path.join(sdk, 'app_mcu')
eide = json.load(open(os.path.join(pdir, '.eide', 'eide.json')))
opts = json.load(open(os.path.join(pdir, '.eide', 'debug.riscv.gcc.options.json')))

norm = lambda p: os.path.normpath(p).replace('\\', '/')
sdk_excl = [norm(e) for e in eide['excludeList'] if not e.startswith('<virtual_root>')]
excl = sdk_excl + ['sample', 'src/main.c']
keep = []                                   # files to keep inside excluded dirs
if not fp:
    excl += ['../platform/component/fingerprint', '../platform/device/fingerprint']
else:
    keep.append('sample/sample_fingerprint.c')
if not voice:
    excl += ['../platform/component/audio']
else:
    keep.append('sample/sample_audio.c')

def under(rel, dirs):
    return any(rel == e or rel.startswith(e + '/') for e in dirs)

excluded = lambda rel: under(rel, excl)

srcs, incs = [], set()
for sd in eide['srcDirs']:
    root = norm(sd)
    for dp, dns, fns in os.walk(os.path.join(pdir, root)):
        dns[:] = sorted(d for d in dns if not d.startswith('.'))
        rel_d = norm(os.path.relpath(dp, pdir))
        if under(rel_d, sdk_excl):          # out of the SDK project itself
            dns[:] = []
            continue
        # Our exclusions keep their header dirs on the include path, exactly
        # as the SDK project has them, so the platform objects are identical.
        if any(f.endswith('.h') and not f.startswith('._') for f in fns):
            incs.add(rel_d)
        for f in sorted(fns):
            if f.startswith('._') or not f.endswith(('.c', '.S', '.s')):
                continue
            rel = norm(os.path.join(rel_d, f))
            if rel in keep or not excluded(rel):
                srcs.append(rel)
srcs.append(norm(os.path.join(ozrel, 'port/ak1037/app/main_ozkie.c')))

dep = eide['dependenceList'][0]['depList'][0]
incs |= {norm(i) for i in dep['incList']}
libdirs = [norm(l) for l in dep['libList']]
defs = dep['defineList']

g, cc, ld = opts['global'], opts['c/cpp-compiler'], opts['linker']
arch = f"-march={g['arch']} -mabi={g['abi']} -mcmodel={g['code-model']}"
cflags = f"{arch} -std={cc['language-c']} -Os -g -Wall {cc['C_FLAGS']}"

objname = lambda s: 'build/' + s.replace('../', 'up_').replace('/', '__').rsplit('.', 1)[0] + '.o'
objs = [objname(s) for s in srcs]
target = f"app_mcu_ozkie_fp{int(fp)}_v{int(voice)}"

with open(out, 'w', newline='\n') as m:
    m.write('# generated by port/ak1037/app/gen_app_mk.py — do not edit\n')
    m.write(f'# OZ_WITH_FP={int(fp)} OZ_WITH_VOICE={int(voice)}\n')
    m.write('TC ?= C:/SysGCC/risc-v/bin/riscv64-unknown-elf-\n')
    m.write('TARGET := ' + target + '\n')
    m.write('CFLAGS := ' + cflags + ' ' + ' '.join('-D' + d for d in defs) + '\n')
    m.write('INCS := ' + ' '.join('-I' + i for i in sorted(incs)) + '\n')
    m.write('LDFLAGS := ' + arch + ' -T ' + norm(eide['compileConfig']['linkerScriptPath'])
            + ' -Wl,-Map=build/$(TARGET).map ' + ' '.join('-L' + l for l in libdirs)
            + ' ' + ld['LIB_FLAGS'] + '\n')
    m.write('OBJS := ' + ' '.join(objs) + '\n\n')
    m.write('all: build/$(TARGET).elf\n\n')
    m.write('build/$(TARGET).elf: $(OBJS)\n')
    m.write('\t$(TC)gcc $(OBJS) $(LDFLAGS) -o $@\n')
    m.write('\t$(TC)size $@\n\n')
    for s, o in zip(srcs, objs):
        m.write(f'{o}: {s}\n\t$(TC)gcc $(CFLAGS) $(INCS) -c $< -o $@\n')

print(f'{target}: {len(srcs)} sources, {len(incs)} include dirs', file=sys.stderr)
